#!/usr/bin/env python3
"""Single source of truth for the Same Boy UI layout.
Generates Resources/plate.png (design with interactive parts inpainted away)
and Source/Layout.h (coordinates used by the editor)."""
import os, cv2, numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# name: (cx, cy, ringRadius)
KNOBS = {
    "env_vol":   (720, 224, 23), "env_pace": (803, 224, 23), "env_len": (886, 224, 23),
    "env_rel":   (886, 312, 23),
    "glide":     (985, 224, 23), "bend": (1078, 224, 23),
    "vib_rate":  (985, 312, 23), "vib_depth": (1059, 312, 23), "vib_delay": (1130, 312, 23),
    "p1_level":  (193, 457, 21), "p1_pace": (194, 584, 22), "p1_shift": (269, 584, 22),
    "p2_level":  (463, 457, 21), "p2_detune": (466, 584, 22), "p2_oct": (543, 584, 22),
    "w_level":   (723, 458, 21), "w_oct": (723, 582, 22),
    "n_level":   (980, 458, 21), "n_pitch": (986, 583, 22),
    "arp_speed": (386, 695, 22), "arp_oct": (623, 695, 21),
    "master":    (1123, 693, 26),
}

# name: (x, y, w, h)  segmented bars
SEGS = {
    "env_dir":     (690, 311, 130, 29),
    "p1_pan":      (249, 452, 140, 25),
    "p1_duty":     (162, 521, 227, 30),
    "p1_sweepdir": (322, 584, 35, 28),
    "p1_sweep":    (357, 584, 35, 28),
    "p2_pan":      (517, 452, 135, 25),
    "p2_duty":     (428, 521, 225, 30),
    "w_pan":       (772, 452, 140, 27),
    "w_shape":     (690, 521, 222, 30),
    "w_vol":       (769, 584, 143, 28),
    "n_pan":       (1030, 452, 128, 27),
    "n_lfsr":      (951, 521, 207, 30),
    "n_track":     (1036, 582, 126, 30),
    "v_mode":      (163, 697, 181, 32),
    "arp_pattern": (433, 697, 155, 32),
    "out_route":   (692, 697, 226, 32),
    "out_pitch":   (931, 697, 139, 32),
}

LEDS = {  # channel enable squares
    "p1_on": (378, 404, 13, 17), "p2_on": (640, 404, 13, 17),
    "w_on": (898, 404, 14, 17), "n_on": (1145, 404, 14, 17),
}
CHTOGGLES = (506, 161, 147, 28)          # P1 P2 WU NZ toggles above scope
SCOPE = (168, 186, 484, 74)
WAVERAM = (168, 288, 484, 72)
WAVENAME = (377, 265, 98, 21)
PRESETNAME = (803, 101, 334, 33)
PRESET_PREV = (770, 97, 33, 41)
PRESET_NEXT = (1137, 97, 33, 41)
FOOTER_LEFT = (165, 363, 200, 15)
FOOTER_LEDS = (510, 363, 143, 15)

CASE = {
    "dpad": (113, 830, 52),
    "select": (690, 828, 42), "start": (802, 822, 42),
    "b": (984, 813, 34), "a": (1100, 813, 34),
}

def main():
    img = cv2.imread(os.path.join(ROOT, "Resources", "design.png"))
    mask = np.zeros(img.shape[:2], np.uint8)
    for cx, cy, r in KNOBS.values():
        m = np.zeros_like(mask)
        cv2.circle(m, (cx, cy), r + 9, 255, -1)
        m[cy + r + 3:, :] = 0
        mask |= m
    def rect(x, y, w, h, pad=4):
        mask[y - pad:y + h + pad, x - pad:x + w + pad] = 255
    for r in SEGS.values(): rect(*r)
    for r in LEDS.values(): rect(*r, pad=3)
    rect(*CHTOGGLES); rect(*SCOPE, pad=0); rect(*WAVERAM, pad=0)
    rect(*WAVENAME, pad=0); rect(*PRESETNAME, pad=0)
    mask[283:290, 168:652] = 255   # gap between wave name and RAM
    # estimate clean LCD background: grey-dilate removes dark ink, then smooth
    bg = cv2.dilate(img, np.ones((41, 41), np.uint8))
    bg = cv2.GaussianBlur(bg, (0, 0), 9).astype(np.float32)
    # match brightness to real background pixels (bright, unmasked)
    g = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    ref = (mask == 0) & (g > np.percentile(g, 40))
    ref[:80, :] = False; ref[760:, :] = False
    w = ref.astype(np.float32)
    diff = (img.astype(np.float32) - bg) * w[..., None]
    ws = cv2.GaussianBlur(w, (0, 0), 14) + 1e-4
    off = cv2.GaussianBlur(diff, (0, 0), 14) / ws[..., None]
    bg = np.clip(bg + off, 0, 255)
    soft = cv2.GaussianBlur(mask.astype(np.float32) / 255, (0, 0), 1.2)[..., None]
    out = (img.astype(np.float32) * (1 - soft) + bg * soft).astype(np.uint8)
    # restore LCD grain inside inpainted areas so patches don't look flat
    rng = np.random.default_rng(4)
    noise = rng.normal(0, 2.2, img.shape[:2]).astype(np.float32)
    noise = cv2.GaussianBlur(noise, (0, 0), 0.6)
    f = out.astype(np.float32)
    sel = mask > 0
    for c in range(3): f[..., c][sel] += noise[sel]
    out = np.clip(f, 0, 255).astype(np.uint8)
    cv2.imwrite(os.path.join(ROOT, "Resources", "plate.png"), out)

    L = ["// Generated by tools/gen_layout.py - do not edit by hand", "#pragma once",
         "#include <juce_graphics/juce_graphics.h>", "namespace layout {",
         "constexpr int W = %d, H = %d;" % (img.shape[1], img.shape[0]),
         "struct KnobPos { const char* id; int cx, cy, r; };",
         "struct SegPos { const char* id; int x, y, w, h; };",
         "inline const KnobPos knobs[] = {"]
    L += ['  {"%s", %d, %d, %d},' % (k, *v) for k, v in KNOBS.items()] + ["};"]
    L += ["inline const SegPos segs[] = {"]
    L += ['  {"%s", %d, %d, %d, %d},' % (k, *v) for k, v in SEGS.items()] + ["};"]
    L += ["inline const SegPos leds[] = {"]
    L += ['  {"%s", %d, %d, %d, %d},' % (k, *v) for k, v in LEDS.items()] + ["};"]
    def R(n, r): return "inline const juce::Rectangle<int> %s { %d, %d, %d, %d };" % (n, *r)
    L += [R("chToggles", CHTOGGLES), R("scope", SCOPE), R("waveRam", WAVERAM),
          R("waveName", WAVENAME), R("presetName", PRESETNAME), R("presetPrev", PRESET_PREV),
          R("presetNext", PRESET_NEXT), R("footerLeft", FOOTER_LEFT), R("footerLeds", FOOTER_LEDS)]
    for k, (cx, cy, r) in CASE.items():
        L.append("inline const juce::Rectangle<int> case_%s { %d, %d, %d, %d };" % (k, cx - r, cy - r, 2 * r, 2 * r))
    L += ["}"]
    open(os.path.join(ROOT, "Source", "Layout.h"), "w").write("\n".join(L) + "\n")

if __name__ == "__main__":
    main()
