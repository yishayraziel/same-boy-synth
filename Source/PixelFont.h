inline float textWidth (const juce::String& s, float px) { return s.length() > 0 ? (s.length() * 6 - 1) * px : 0.0f; }

// Draws upper-case pixel text; px = size of one font pixel. Returns width.
inline float draw (juce::Graphics& g, const juce::String& text, float x, float y, float px)
{
    const auto up = text.toUpperCase();
    juce::RectangleList<float> rl;
    for (int i = 0; i < up.length(); ++i)
    {
        if (auto* gl = find ((char) up[i]))
            for (int r = 0; r < 7; ++r)
                for (int c = 0; c < 5; ++c)
                    if (gl->rows[r][c] == '#')
                        rl.addWithoutMerging ({ x + (i * 6 + c) * px, y + r * px, px + 0.05f, px + 0.05f });
    }
    g.fillRectList (rl);
    return textWidth (up, px);
}

inline void drawCentred (juce::Graphics& g, const juce::String& text, juce::Rectangle<float> area, float px)
{
    const float w = textWidth (text, px);
    draw (g, text, std::round (area.getCentreX() - w * 0.5f), std::round (area.getCentreY() - 3.5f * px), px);
}
